#!/usr/bin/env python3
"""Biped central pattern generator (CPG) and limb kinematics.

Converts high-level HumanIntent into coordinated human joint trajectories.

Biological & Kinematic Foundations:
  1. Spinal Biped CPG:
     In humans, locomotor rhythm is generated by spinal interneuronal networks
     in the lumbar enlargement (L1-S2), organized as mutually inhibitory flexor-extensor
     and left-right half-centers (Grillner 2006, Kiehn 2016).
     Under normal neurochemical conditions (intact GABAergic commissural inhibition),
     left and right lower limb oscillators lock into strict anti-phase synchrony (Delta phi = pi).
     Pharmacological GABA_A antagonism attenuates this commissural coupling (PDF Eq. 5),
     inducing phase jitter, asynchronous stepping, and ataxic staggering.

  2. Lower Limb Kinematics (Human Clinical Gait):
     Each gait cycle per leg consists of:
     - Stance Phase (~60% of cycle, phi in [0, pi)):
       Weight acceptance, midstance forward roll, and terminal push-off.
       Hip retracts (positive forward flexion -> negative posterior extension),
       pushing backward against ground friction to propel the center of mass (COM) forward.
       Knee provides shock-absorbing compliance then extends for weight-bearing.
     - Swing Phase (~40% of cycle, phi in [pi, 2*pi)):
       Foot lift-off, rapid knee flexion (up to ~60 deg / 1.05 rad) for toe clearance,
       ankle dorsiflexion, and forward hip protraction to prepare for the next heel strike.

  3. Upper Body Counter-Balance (Arm Swing):
     Contralateral arm swing (left arm in phase with right leg, right arm in phase with
     left leg) naturally counteracts vertical-axis angular momentum of the pelvis/torso,
     reducing whole-body metabolic cost and maintaining heading stability (Meyns et al. 2013).

  4. Pathological Perturbations:
     - Na_v channel block (Lidocaine / local anesthetics):
       Reduces motor tone and extensor force capacity -> knee buckling, stance crouching,
       and diminished stride length.
     - GABA_A block (Rdl / picrotoxin):
       Weakens reciprocal coupling -> inter-leg phase drift and ataxic stumbling.
"""
