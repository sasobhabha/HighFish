from sim.fish_readout import HumanIntent

# Joint names matching the humanoid scaffold
HUMANOID_JOINTS = [
    "left_hip_pitch", "left_hip_roll", "left_knee", "left_ankle",
    "right_hip_pitch", "right_hip_roll", "right_knee", "right_ankle",
    "left_shoulder_pitch", "left_elbow",
    "right_shoulder_pitch", "right_elbow",
]


class BipedCPG:
    """2-oscillator coupled phase CPG for biped locomotion (PDF Eqs. 4-5 analogue).

    Equations:
      dphi_L/dt = 2*pi*nu + w_c * sin(phi_R - phi_L - pi) + noise
      dphi_R/dt = 2*pi*nu + w_c * sin(phi_L - phi_R - pi) + noise
      where w_c = w0 * intent.coordination
    """

    def __init__(self, w0: float = 6.0, seed: int = 0):
        self.w0 = w0
        # Initialize in canonical anti-phase: Left at 0, Right at pi
        self.phi_l = 0.0
        self.phi_r = float(np.pi)
        self.rng = np.random.default_rng(seed)

    def reset(self, seed: int | None = None):
        if seed is not None:
            self.rng = np.random.default_rng(seed)
        self.phi_l = 0.0
        self.phi_r = float(np.pi)

    def step(self, dt: float, intent: HumanIntent) -> tuple[float, float]:
        """Advances CPG phases based on intent cadence and coordination strength."""
        if intent.freeze or intent.mode in ("freeze", "stand"):
            return self.phi_l, self.phi_r

        # CPG phase advance: cadence_scale moderates the step rate for the
        # unassisted biped (fast long strides are unmatched by balance).
        nu = float(np.clip(intent.cadence * getattr(self, "cadence_scale", 1.0), 0.2, 2.5))
        # Reciprocal coupling attenuated by GABA_A antagonism
        w = self.w0 * float(np.clip(intent.coordination, 0.0, 1.0))

        # Under low coordination (ataxic regime), inject stochastic phase noise
        noise_l, noise_r = 0.0, 0.0
        if intent.coordination < 0.60:
            sigma = 4.0 * (1.0 - intent.coordination)
            noise_l = float(self.rng.normal(0, sigma))
            noise_r = float(self.rng.normal(0, sigma))

        # Coupled phase dynamics
        dphi_l = 2 * np.pi * nu + w * np.sin(self.phi_r - self.phi_l - np.pi) + noise_l
        dphi_r = 2 * np.pi * nu + w * np.sin(self.phi_l - self.phi_r - np.pi) + noise_r

        self.phi_l = float((self.phi_l + dt * dphi_l) % (2 * np.pi))
        self.phi_r = float((self.phi_r + dt * dphi_r) % (2 * np.pi))
        return self.phi_l, self.phi_r

    def phase_sync_error(self) -> float:
        """Normalized anti-phase coordination error in [0, 1].

        0.0 = perfect anti-phase (Delta phi = pi).
        1.0 = completely in-phase (hopping) or orthogonal drift.
        """
        diff = self.phi_l - self.phi_r - np.pi
        return float(abs(np.angle(np.exp(1j * diff))) / np.pi)


class BipedGaitKinematics:
    """Translates biped CPG phases + HumanIntent into humanoid joint angles."""

    # Nominal joint motion amplitudes (radians) for standard walking at human scale
    A_HIP_PITCH = 0.58          # ~33 deg hip flexion/extension stroke (stride length 1.35-1.45m)
    A_KNEE_SWING = 1.22         # ~70 deg knee flexion during swing for clean foot clearance
    A_ANKLE_PITCH = 0.28        # ~16 deg ankle pitch
    A_ARM_SWING = 0.42          # Counter-balancing shoulder pitch
    A_HIP_YAW_TURN = 0.15       # Yaw turn bias

    # Max slew rate for actuator targets (rad/s) to prevent instantaneous torque spikes.
    # Freejoint mode uses a tighter cap: violent target slews translate
    # directly into free-body angular momentum the balance layer cannot
    # absorb (in harness mode the rail does).
    MAX_TARGET_SPEED = 25.0
    MAX_TARGET_SPEED_2D = 8.0

    def __init__(self):
        self.prev_targets: dict[str, float] = {j: 0.0 for j in HUMANOID_JOINTS}
        # Gait-initiation ramp: stride amplitude scales 0 -> 1 over this many
        # seconds once walking starts (real humans reach steady gait over
        # ~0.3-0.6 s; Winter Ch. 4). 0.0 disables. Set by the pipeline in
        # freejoint (unharnessed) mode where the instantaneous full CPG
        # amplitude at t=0 kicks the biped off balance.
        self.start_ramp: float = 0.0
        self._t_active: float = 0.0
        # Effective per-step target slew cap (rad/s); instance-level so the
        # freejoint pipeline can tighten it (see MAX_TARGET_SPEED_2D).
        self.max_slew: float = self.MAX_TARGET_SPEED
        # Stride amplitude scale (0-1): freejoint biped uses a moderated
        # stride; full readout stride (1.4 clip) overswings the unassisted
        # body beyond what balance can control.
        self.        stride_scale: float = 1.0
        # Step-rate scale for the unassisted biped (see step()); CPG nu is
        # multiplied by this before clipping.
        cadence_scale: float = 1.0
        # Gait-shape knobs (freejoint): stance knee flexion base (real walking
        # has ~15 deg weight-acceptance flexion; a rigid-straight stance leg
        # turns each step into a pogo hop) and ankle push-off scale (large
        # push-off keeps the body airborne = flight phase).
        self.stance_flex: float = 0.04
        self.push_scale: float = 1.0
        # Neutral rest pose
        self.rest_angles: dict[str, float] = {
            "left_hip_pitch": 0.0,
            "left_hip_roll": 0.0,
            "left_knee": 0.0,
            "left_ankle": 0.0,
            "right_hip_pitch": 0.0,
            "right_hip_roll": 0.0,
            "right_knee": 0.0,
            "right_ankle": 0.0,
            "left_shoulder_pitch": 0.0,
            "left_elbow": 0.15,
            "right_shoulder_pitch": 0.0,
            "right_elbow": 0.15,
        }
        self.prev_targets = dict(self.rest_angles)

    def reset(self):
        self.prev_targets = dict(self.rest_angles)
        self._t_active = 0.0

    def compute_joint_targets(
        self,
        dt: float,
        phi_l: float,
        phi_r: float,
        intent: HumanIntent,
    ) -> dict[str, float]:
        """Computes instantaneous position targets for all actuated joints.

        Args:
            dt: Time increment in seconds.
            phi_l: Left leg CPG phase in [0, 2*pi).
            phi_r: Right leg CPG phase in [0, 2*pi).
            intent: Current HumanIntent instance.

        Returns:
            Dictionary mapping joint name to target angle in radians.
        """
        targets = dict(self.rest_angles)

        # Stand or freeze mode: hold erect rest posture
        if intent.freeze or intent.mode in ("freeze", "stand") or intent.forward_drive < 0.05:
            # Postural buckling if motor tone is severely impaired
            buckle = float(np.clip(1.0 - intent.posture_height, 0.0, 0.8))
            targets["left_knee"] = 0.0 + 0.40 * buckle
            targets["right_knee"] = 0.0 + 0.40 * buckle
            targets["left_hip_pitch"] = -0.15 * buckle
            targets["right_hip_pitch"] = -0.15 * buckle
            targets["left_shoulder_pitch"] = 0.0
            targets["right_shoulder_pitch"] = 0.0
            targets["left_elbow"] = 0.15
            targets["right_elbow"] = 0.15
            targets["rail_vx"] = 0.0
            return self._apply_slew_limit(targets, dt)

        # Scaled amplitudes from motor intent
        stride = float(np.clip(intent.stride_length, 0.0, 1.4)) * self.stride_scale

        # Gait-initiation ramp: ease stride amplitude in over start_ramp s
        self._t_active += dt
        if self.start_ramp > 0.0:
            ramp = float(np.clip(self._t_active / self.start_ramp, 0.0, 1.0))
            stride *= 0.2 + 0.8 * ramp

        turn = float(np.clip(intent.turn_intent, -1.0, 1.0))
        posture = float(np.clip(intent.posture_height, 0.2, 1.0))
        tone = float(np.clip(intent.motor_tone, 0.1, 1.0))

        # Forward velocity target (sane adult human walking speed: ~1.20 - 1.25 m/s at nominal forward drive and tone)
        drive_norm = float(np.clip(intent.forward_drive / 0.535, 0.0, 2.0))
        v_des = 1.12 * drive_norm * tone
        targets["rail_vx"] = v_des

        # Differential stride for steering: outer leg takes longer strides
        # turn > 0: turning right -> left leg (outer) strides longer
        stride_l = stride * (1.0 + 0.35 * turn)
        stride_r = stride * (1.0 - 0.35 * turn)

        # Knee stance flexion (shock absorption + crouch under low posture)
        knee_stance = self.stance_flex + 0.35 * (1.0 - posture)

        # Compute leg joints for a given phase
        def _leg_kinematics(phi: float, s: float) -> tuple[float, float, float]:
            """Returns (hip_pitch, knee, ankle_pitch) for phase phi."""
            # Stance: phi in [0, pi)
            # Heel strike at phi=0: hip flexed forward (+A_HIP)
            # Toe-off at phi=pi: hip extended backward (-A_HIP)
            # Swing: phi in [pi, 2*pi)
            # Knee flexes high to clear the floor; hip swings forward
            hip = self.A_HIP_PITCH * s * np.cos(phi)
            if phi < np.pi:
                # Stance phase: knee extended for weight support, slight shock absorption
                knee = knee_stance + 0.06 * s * np.sin(phi)
                # Ankle push-off in late stance: delivers forward thrust against the floor
                if phi > 0.3 * np.pi:
                    p_factor = (phi - 0.3 * np.pi) / (0.7 * np.pi)
                    ankle = float(self.push_scale * 0.35 * s * np.sin(p_factor * np.pi))
                else:
                    ankle = -0.04 * s * np.sin(phi / (0.3 * np.pi) * np.pi)
            else:
                # Swing phase: knee flexes and ankle dorsiflexes (toes lift) for foot ground clearance
                sw_phase = float(np.clip(phi - np.pi, 0.0, np.pi))
                knee = knee_stance + (self.A_KNEE_SWING * s * (np.sin(sw_phase) ** 1.3))
                ankle = float(-0.25 * s * np.sin(sw_phase))
            return float(hip), float(knee), float(ankle)

        hl, kl, al = _leg_kinematics(phi_l, stride_l)
        hr, kr, ar = _leg_kinematics(phi_r, stride_r)

        # Apply motor tone scaling: weak muscles cannot produce full joint ranges
        hl *= tone
        kl = knee_stance + (kl - knee_stance) * tone
        al *= tone
        hr *= tone
        kr = knee_stance + (kr - knee_stance) * tone
        ar *= tone

        targets["left_hip_pitch"] = hl
        targets["left_knee"] = kl
        targets["left_ankle"] = al
        targets["right_hip_pitch"] = hr
        targets["right_knee"] = kr
        targets["right_ankle"] = ar

        # Lateral hip roll: slight outward abduction for clearance + turn trimming
        targets["left_hip_roll"] = 0.02 + 0.05 * max(0.0, turn)
        targets["right_hip_roll"] = 0.02 + 0.05 * max(0.0, -turn)

        # Upper body counter-balance: arms swing anti-phase to ipsilateral leg
        # (left arm swings with right leg, right arm with left leg)
        targets["left_shoulder_pitch"] = -hl * 0.70
        targets["right_shoulder_pitch"] = -hr * 0.70
        targets["left_elbow"] = 0.35 + 0.15 * np.sin(phi_r)
        targets["right_elbow"] = 0.35 + 0.15 * np.sin(phi_l)

        return self._apply_slew_limit(targets, dt)

    def _apply_slew_limit(self, targets: dict[str, float], dt: float) -> dict[str, float]:
        """Enforces actuator velocity limits to ensure numerical stability."""
        max_d = self.max_slew * dt
        limited = {}
        for k, v in targets.items():
            if k == "rail_vx":
                limited[k] = v
                continue
            prev = self.prev_targets.get(k, v)
            delta = v - prev
            if delta > max_d:
                val = prev + max_d
            elif delta < -max_d:
                val = prev - max_d
            else:
                val = v
            limited[k] = val
        self.prev_targets = dict(limited)
        return limited


